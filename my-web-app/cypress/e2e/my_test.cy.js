it('Нүүр хуудаснаас бараа олж сагсанд нэмэх', () => {
  cy.visit('http://localhost:3000');

  // 1. "Сагсанд нэмэх" товчийг дарна
  cy.contains(/Add to Cart|Сагсанд нэмэх/i).first().click();

  // 2. Сагсны тоолуур нэмэгдсэн эсэхийг шалгана
  // МУЙ-ийн класс хайхын оронд баруун дээд булан дахь текстийг шалгая.
  // Жишээ нь: "Cart (1)" эсвэл "Carc (1)" байгааг шалгана.
  // cy.get('.MuiBadge-badge').should('not.contain', '0'); <-- Энийг устгана
  
  // Оронд нь үүнийг бичээрэй:
  cy.get('button').contains(/Cart|Carc/i).should('contain', '1'); 
});